import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

// Never read the developer's real conversation store: see scan.test.mjs.
process.env.DSH_HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'aiignore-home-'));

const { apply, aiignoreRules } = await import('../index.js');

function workspace() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'aiignore-rules-'));
  fs.writeFileSync(path.join(root, 'app.js'), 'export const a = 1;\n');
  fs.writeFileSync(path.join(root, '.aiignore'), [
    '# Files that waste an AI coding agent\'s context.',
    '# Generated by ai-context-doctor. Review before committing.',
    '',
    'dist/',
    '*.log',
    'package-lock.json',
    ''
  ].join('\n'));
  return root;
}

function fakeResponse() {
  return {
    status: 0,
    body: '',
    writeHead(status) {
      this.status = status;
    },
    setHeader() {},
    end(body) {
      this.body = body;
    }
  };
}

function fakeRequest({ method = 'GET', url = '/', body } = {}) {
  const request = new EventEmitter();
  request.method = method;
  request.url = url;
  request.headers = { host: '127.0.0.1:1234' };
  if (body !== undefined) {
    request.setEncoding = () => {};
    process.nextTick(() => {
      request.emit('data', body);
      request.emit('end');
    });
  }
  return request;
}

function harness(options = {}) {
  const routes = new Map();
  const ctx = {
    tools: { guard() {} },
    webServer: {
      register(route) {
        routes.set(route.path, route.handler);
        return () => routes.delete(route.path);
      }
    },
    on() {},
    inject(deps, callback) {
      if (deps.every((dep) => ctx[dep] !== undefined)) callback(ctx);
    }
  };
  apply(ctx, options);
  return routes;
}

const call = (routes, route, options) =>
  new Promise((resolve) => {
    const response = fakeResponse();
    routes.get(route)(fakeRequest(options), response);
    const done = () => resolve({ status: response.status, body: response.body === '' ? null : JSON.parse(response.body) });
    if (response.body === '') response.end = (body) => { response.body = body; resolve({ status: response.status, body: JSON.parse(body) }); };
    setTimeout(done, 40);
  });

test('the rules list drops comments and blank lines but keeps what is in force', () => {
  const root = workspace();
  assert.deepEqual(aiignoreRules(root), ['dist/', '*.log', 'package-lock.json']);
  assert.deepEqual(aiignoreRules(path.join(root, 'nope')), []);
});

test('the report carries the rules it is scoring against', async () => {
  const root = workspace();
  const routes = harness({ home: process.env.DSH_HOME });
  await call(routes, '/aiignore/scan', { method: 'POST', url: `/aiignore/scan?cwd=${encodeURIComponent(root)}`, body: '{}' });
  const { status, body } = await call(routes, '/aiignore/report', { url: `/aiignore/report?cwd=${encodeURIComponent(root)}` });
  assert.equal(status, 200);
  assert.deepEqual(body.rules, ['dist/', '*.log', 'package-lock.json']);
});

test('removing one rule edits exactly that line and leaves the comments alone', async () => {
  const root = workspace();
  const routes = harness({ home: process.env.DSH_HOME });
  const { status, body } = await call(routes, '/aiignore/rules/delete', {
    method: 'POST',
    url: `/aiignore/rules/delete?cwd=${encodeURIComponent(root)}`,
    body: JSON.stringify({ rule: '*.log' })
  });

  assert.equal(status, 200);
  assert.equal(body.removed, true);
  const text = fs.readFileSync(path.join(root, '.aiignore'), 'utf8');
  assert.ok(text.includes('Generated by ai-context-doctor'));
  assert.ok(text.includes('dist/'));
  assert.ok(text.includes('package-lock.json'));
  assert.ok(!text.includes('*.log\n'));
  assert.deepEqual(aiignoreRules(root), ['dist/', 'package-lock.json']);
});

test('a rule that is not there is refused, and GET is not allowed', async () => {
  const root = workspace();
  const routes = harness({ home: process.env.DSH_HOME });

  const wrong = await call(routes, '/aiignore/rules/delete', {
    method: 'POST',
    url: `/aiignore/rules/delete?cwd=${encodeURIComponent(root)}`,
    body: JSON.stringify({ rule: 'nothing-like-this/' })
  });
  assert.equal(wrong.status, 404);
  assert.equal(wrong.body.error, 'no-such-rule');

  const get = await call(routes, '/aiignore/rules/delete', { url: `/aiignore/rules/delete?cwd=${encodeURIComponent(root)}` });
  assert.equal(get.status, 405);
});
